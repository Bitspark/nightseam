// Package spec renders a family as its specification: one Markdown
// document per family, from every tier it declares — the types with their
// fields and constraints, the two sides with their operations and errors,
// the parameters it is generic in, the governance of a session of it —
// so that what a family means is written once, in the declaration, and
// the document is never behind it. It implements spi.Target and reserves
// nothing: it declares no identifier a family could collide with.
package spec

import (
	"fmt"
	"path"
	"regexp"
	"sort"
	"strings"

	"github.com/Bitspark/nightseam/internal/diag"
	"github.com/Bitspark/nightseam/internal/emit"
	"github.com/Bitspark/nightseam/internal/model"
	"github.com/Bitspark/nightseam/internal/render"
	"github.com/Bitspark/nightseam/internal/spi"
)

// Config places the documents: Layout is where a family's document lives,
// as a pattern over the family's name; Place puts named families elsewhere.
type Config struct {
	Layout string
	Place  map[string]string
}

// DefaultLayout is api/spec/<family>, holding README.md.
const DefaultLayout = "api/spec/{family}"

// Name is the target's name.
const Name = "spec"

// File is the document's name within the family's directory.
const File = "README.md"

// New returns the spec target with its config.
func New(c Config) spi.Target {
	if c.Layout == "" {
		c.Layout = DefaultLayout
	}
	return &target{c}
}

type target struct{ config Config }

var pathPattern = regexp.MustCompile(`^[A-Za-z0-9_][A-Za-z0-9_./{}-]*$`)

// Validate reports what is wrong with the config.
func (c Config) Validate() error {
	patterns := []string{c.Layout}
	for _, placed := range c.Place {
		patterns = append(patterns, placed)
	}
	for _, pattern := range patterns {
		if !strings.Contains(pattern, "{family}") {
			return fmt.Errorf("a layout pattern names the family with {family}: %q", pattern)
		}
		dir := strings.ReplaceAll(pattern, "{family}", "x")
		if dir == "." || dir == ".." || strings.Contains(dir, "\\") || strings.Contains(dir, ":") || strings.HasPrefix(dir, "/") || path.Clean(dir) != dir || strings.HasPrefix(dir, "../") || !pathPattern.MatchString(dir) {
			return fmt.Errorf("invalid output path pattern %q", pattern)
		}
	}
	return nil
}

func (c Config) dir(family string) string {
	if placed, ok := c.Place[family]; ok {
		return strings.ReplaceAll(placed, "{family}", family)
	}
	return strings.ReplaceAll(c.Layout, "{family}", family)
}

func (*target) Name() string { return Name }

// Consumes is every concern: a specification documents all of them.
func (*target) Consumes() []spi.Concern { return []spi.Concern{spi.Model, spi.Protocol, spi.Session} }

func (t *target) Owns(family string) []string { return []string{t.config.dir(family)} }

func (t *target) Roots() []string {
	seen := map[string]bool{spi.PatternRoot(t.config.Layout): true}
	roots := []string{spi.PatternRoot(t.config.Layout)}
	for _, placed := range t.config.Place {
		if root := spi.PatternRoot(placed); !seen[root] {
			seen[root] = true
			roots = append(roots, root)
		}
	}
	sort.Strings(roots)
	return roots
}

func (t *target) Family(p string) (string, bool) {
	for family, placed := range t.config.Place {
		if matched, ok := spi.MatchPattern(placed, p); ok && matched == family {
			return family, true
		}
	}
	if family, ok := spi.MatchPattern(t.config.Layout, p); ok {
		if _, placed := t.config.Place[family]; !placed {
			return family, true
		}
	}
	return "", false
}

// Check has nothing to refuse: a document is written of any family the
// neutral checks accept.
func (t *target) Check(f *render.Family) []diag.Diagnostic {
	if err := t.config.Validate(); err != nil {
		return []diag.Diagnostic{{Family: f.Name, Code: "invalid_config", Message: err.Error()}}
	}
	return nil
}

// Reserved is what the target reserves: nothing.
func Reserved() []string { return nil }

// Render emits the family's document.
func (t *target) Render(f *render.Family) ([]spi.File, error) {
	if err := t.config.Validate(); err != nil {
		return nil, err
	}
	w := emit.NewWriter("")
	d := &doc{f: f, w: w}
	d.render()
	return []spi.File{{Path: path.Join(t.config.dir(f.Name), File), Data: []byte(w.String())}}, nil
}

type doc struct {
	f *render.Family
	w *emit.Writer
}

func (d *doc) line(text string)                 { d.w.Line(text) }
func (d *doc) linef(format string, args ...any) { d.w.Linef(format, args...) }

func (d *doc) render() {
	f := d.f
	d.linef("# %s", f.Name)
	d.line("")
	d.line("<!-- Generated by nightseam from api/contracts/" + f.Name + "/; do not edit. -->")
	d.line("")
	d.linef("A family of the `nightseam.duplex/1` profile, declared in %s.", d.tiers())
	if len(f.References) > 0 {
		d.linef("It imports %s.", d.families(f.References))
	}
	if f.Generic {
		d.line("")
		d.line("## Parameters")
		d.line("")
		d.line("The family is generic in the families bound to these parameters, where its generated code is instantiated:")
		d.line("")
		for _, p := range f.Parameters {
			var drawn []string
			for _, use := range p.Uses {
				drawn = append(drawn, "`"+use.Type+"`")
			}
			d.linef("- **%s**, of the `%s` role, drawn at %s.%s", p.Name, p.Of, strings.Join(drawn, ", "), suffix(p.Description))
		}
	}
	d.types()
	if f.HasProtocol() {
		d.side("Server", "The server implements these methods and emits these events.", f.Server)
		d.side("Client", "The client implements these methods, which the server calls, and emits these events.", f.Client)
		if len(f.Errors) > 0 {
			d.line("")
			d.line("## Errors")
			d.line("")
			d.line("The public errors of the family, by code: what a call may fail with.")
			d.line("")
			d.line("| Code | Description |")
			d.line("|---|---|")
			for _, e := range f.Errors {
				d.linef("| `%s` | %s |", e.Code, cell(e.Description))
			}
		}
	}
	if s := f.Session; s != nil {
		d.line("")
		d.line("## Session")
		d.line("")
		d.line("How a session of the family is governed.")
		d.line("")
		d.linef("- **Decides**: %s — the methods that need control to send.", codes(s.Decides))
		d.linef("- **Asks**: %s — the methods the server sends that raise a request the holder of control must answer.", codes(s.Asks))
		if s.Conversation != nil {
			d.linef("- **Conversation**: the id arrives in the `%s` event, at `%s` of its data.", s.Conversation.Event, s.Conversation.Path)
		}
	}
}

func (d *doc) tiers() string {
	var names []string
	for _, file := range d.f.Files {
		names = append(names, "`"+file+"`")
	}
	return strings.Join(names, ", ")
}

func (d *doc) families(names []string) string {
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

func (d *doc) types() {
	f := d.f
	var own []*render.Type
	for _, t := range f.Types {
		if !t.Injected {
			own = append(own, t)
		}
	}
	if len(own) == 0 {
		return
	}
	d.line("")
	d.line("## Types")
	for _, t := range own {
		d.line("")
		d.linef("### %s", t.Name)
		d.line("")
		what := t.Kind
		if t.Kind == "entity" {
			what = "entity, identified by `" + t.Key + "`"
		}
		if t.Open {
			what += ", open: fields beyond the declared ones are kept"
		}
		if len(t.Uses) > 0 {
			var names []string
			for _, use := range t.Uses {
				names = append(names, "`"+use.Parameter+"."+use.Type+"`")
			}
			what += ", generic in " + strings.Join(names, ", ")
		}
		d.linef("%s %s.%s", article(what), what, suffix(t.Description))
		switch t.Kind {
		case "record", "entity":
			if len(t.Fields) == 0 {
				continue
			}
			d.line("")
			d.line("| Field | Type | Presence | Constraints | Description |")
			d.line("|---|---|---|---|---|")
			for _, field := range t.Fields {
				presence := "required"
				if !field.Required {
					presence = "optional"
				}
				if field.Nullable {
					presence += ", nullable"
				}
				description := field.Description
				if field.Owner != t.Name {
					description = strings.TrimSpace("inherited from `" + field.Owner + "`. " + description)
				}
				d.linef("| `%s` | %s | %s | %s | %s |", field.Name, spell(field.Type), presence, constraints(field), cell(description))
			}
		case "enum":
			var values []string
			for _, value := range t.Values {
				values = append(values, "`"+value+"`")
			}
			d.line("")
			d.linef("One of %s.", strings.Join(values, ", "))
		case "alias":
			d.line("")
			d.linef("An alias of %s.", spell(t.Alias))
		}
	}
	if len(f.Types) > len(own) {
		d.line("")
		d.line("Every family with a protocol also carries `Envelope`, one message of the profile, and `Handle`, a reference to a channel that speaks it.")
	}
}

func (d *doc) side(name, intro string, side render.Side) {
	if len(side.Methods) == 0 && len(side.Events) == 0 {
		return
	}
	d.line("")
	d.linef("## %s side", name)
	d.line("")
	d.line(intro)
	if len(side.Methods) > 0 {
		d.line("")
		d.line("| Method | Request | Result | Errors | Description |")
		d.line("|---|---|---|---|---|")
		for _, m := range side.Methods {
			request := "—"
			if m.Request != nil {
				request = spell(m.Request)
			}
			d.linef("| `%s` | %s | %s | %s | %s |", m.Name, request, spell(m.Result), codes(m.Errors), cell(m.Description))
		}
	}
	if len(side.Events) > 0 {
		d.line("")
		d.line("| Event | Data | Description |")
		d.line("|---|---|---|")
		for _, e := range side.Events {
			d.linef("| `%s` | %s | %s |", e.Name, spell(e.Type), cell(e.Description))
		}
	}
}

// spell writes a type expression as the document reads it.
func spell(e model.TypeExpr) string {
	switch x := e.(type) {
	case model.Primitive:
		return "`" + string(x) + "`"
	case model.Named:
		return "`" + x.Name + "`"
	case model.Imported:
		return "`" + x.Family + "." + x.Name + "`"
	case model.Drawn:
		return "`" + x.Parameter + "." + x.Name + "`"
	case model.Array:
		return "array of " + spell(x.Elem)
	case model.Map:
		return "map of " + spell(x.Elem)
	case model.Ref:
		return "reference to `" + x.Entity + "`"
	case model.Apply:
		var with []string
		for _, parameter := range sortedKeys(x.With) {
			with = append(with, parameter+"="+x.With[parameter].String())
		}
		return "`" + x.Family + "." + x.Name + "` with " + strings.Join(with, ", ")
	}
	return "`" + model.String(e) + "`"
}

// article is the indefinite article a word takes.
func article(word string) string {
	if strings.ContainsRune("aeiou", rune(word[0])) {
		return "An"
	}
	return "A"
}

// constraints lists a field's constraints, or nothing.
func constraints(field render.Field) string {
	var out []string
	if field.Unique {
		out = append(out, "unique")
	}
	if field.Min != nil {
		out = append(out, "min "+field.Min.String())
	}
	if field.Max != nil {
		out = append(out, "max "+field.Max.String())
	}
	if field.Length != nil {
		if field.Length.Min != nil {
			out = append(out, fmt.Sprintf("length ≥ %d", *field.Length.Min))
		}
		if field.Length.Max != nil {
			out = append(out, fmt.Sprintf("length ≤ %d", *field.Length.Max))
		}
	}
	if field.Pattern != "" {
		out = append(out, "matches `"+field.Pattern+"`")
	}
	if len(out) == 0 {
		return "—"
	}
	return cell(strings.Join(out, ", "))
}

func codes(names []string) string {
	if len(names) == 0 {
		return "—"
	}
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

// cell makes text safe in a table cell.
func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(text), "|", "\\|"), "\n", " ")
}

// suffix appends a description as a second sentence, or nothing.
func suffix(description string) string {
	if strings.TrimSpace(description) == "" {
		return ""
	}
	return " " + strings.TrimSpace(description)
}

func sortedKeys(m map[string]model.Filler) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
