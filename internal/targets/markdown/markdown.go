// Package markdown writes the document as Markdown: one page per family,
// README.md under api/spec/<family>, which renders where the tree is read —
// the types with their fields and constraints, an example of each and
// where it is used, the two sides with their operations and errors and each
// operation as the frames of the profile carry it, the parameters a family
// is generic in, the governance of a session of it — so that what a family
// means is written once, in the declaration, and the page is never behind
// it. It is a doc.Writer, a target by doc.Target, and reserves nothing: it
// declares no identifier a family could collide with.
package markdown

import (
	"bytes"
	"encoding/json"
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/Bitspark/nightseam/internal/doc"
	"github.com/Bitspark/nightseam/internal/emit"
	"github.com/Bitspark/nightseam/internal/model"
	"github.com/Bitspark/nightseam/internal/spi"
)

// Config places the pages: Layout is where a family's page lives, as a
// pattern over the family's name; Place puts named families elsewhere.
type Config struct {
	Layout string
	Place  map[string]string
}

// DefaultLayout is api/spec/<family>, holding README.md.
const DefaultLayout = "api/spec/{family}"

// Name is the writer's name, and its target's.
const Name = "markdown"

// File is the page's name within the family's directory.
const File = "README.md"

// New returns the Markdown writer with its config.
func New(c Config) doc.Writer {
	if c.Layout == "" {
		c.Layout = DefaultLayout
	}
	return &writer{c}
}

type writer struct{ config Config }

func (*writer) Name() string { return Name }

func (w *writer) Layout() doc.Layout {
	return doc.Layout{Family: w.config.Layout, Place: w.config.Place}
}

// Reserved is what the writer reserves: nothing.
func Reserved() []string { return nil }

// Checkout writes no page of the checkout as a whole.
func (*writer) Checkout(*doc.Checkout) ([]spi.File, error) { return nil, nil }

// Family writes the family's page.
func (w *writer) Family(f *doc.Family) ([]spi.File, error) {
	out := emit.NewWriter("")
	p := &page{f: f, w: out}
	p.render()
	return []spi.File{{Path: path.Join(w.Layout().Dir(f.Name), File), Data: []byte(out.String())}}, nil
}

type page struct {
	f *doc.Family
	w *emit.Writer
}

func (p *page) line(text string)                 { p.w.Line(text) }
func (p *page) linef(format string, args ...any) { p.w.Linef(format, args...) }

func (p *page) render() {
	f := p.f
	p.linef("# %s", f.Name)
	p.line("")
	p.line("<!-- Generated by nightseam from " + p.source() + "; do not edit. -->")
	p.line("")
	p.linef("A family of the `nightseam.duplex/1` profile, declared in %s.", p.tiers())
	if len(f.Imports) > 0 {
		p.linef("It imports %s.", p.families(f.Imports))
	}
	if len(f.Carries) > 0 {
		p.linef("The tiers it declares bring the built-in %s, imported implicitly.", p.list(f.Carries, "family", "families"))
	}
	if len(f.Parameters) > 0 {
		p.line("")
		p.line("## Parameters")
		p.line("")
		p.line("The family is instantiated by filling these parameters:")
		p.line("")
		for _, parameter := range f.Parameters {
			p.parameter(parameter)
		}
	}
	p.types()
	if f.Protocol {
		p.side("Server", "The server implements these methods and emits these events.", f.Server)
		p.side("Client", "The client implements these methods, which the server calls, and emits these events.", f.Client)
		if len(f.Errors) > 0 {
			p.line("")
			p.line("## Errors")
			p.line("")
			p.line("The public errors of the family, by code: what a call may fail with.")
			p.line("")
			p.line("| Code | Description |")
			p.line("|---|---|")
			for _, e := range f.Errors {
				p.linef("| `%s` | %s |", e.Code, cell(e.Description))
			}
		}
	}
	if s := f.Session; s != nil {
		p.line("")
		p.line("## Session")
		p.line("")
		p.line("How a session of the family is governed.")
		p.line("")
		for _, inherited := range s.Inherited {
			p.linef("Governance inherited from the %s side of `%s`.", inherited.Side, inherited.Family)
		}
		if len(s.Inherited) > 0 {
			p.line("")
		}
		p.linef("- **Decides**: %s — the methods that need control to send.", codes(s.Decides))
		p.linef("- **Asks**: %s — the methods the server sends that raise a request the holder of control must answer.", codes(s.Asks))
		if s.Conversation != nil {
			p.linef("- **Conversation**: the id arrives in the `%s` event, at `%s` of its data.", s.Conversation.Event, s.Conversation.Path)
		}
	}
}

func (p *page) source() string {
	if p.f.Source != "" {
		return strings.TrimSuffix(p.f.Source, "/") + "/"
	}
	return "api/contracts/" + p.f.Name + "/"
}

func (p *page) parameter(parameter doc.Parameter) {
	meaning := "a type"
	if parameter.Of != "" {
		meaning = "a family with the `" + parameter.Of + "` tier"
		if len(parameter.Drawn) > 0 {
			var drawn []string
			for _, name := range parameter.Drawn {
				drawn = append(drawn, "`"+name+"`")
			}
			meaning += ", drawn at " + strings.Join(drawn, ", ")
		}
	}
	p.linef("- **%s**: %s.%s", parameter.Name, meaning, suffix(parameter.Description))
}

func (p *page) tiers() string {
	var names []string
	for _, file := range p.f.Files {
		if source := p.source(); source != "api/contracts/"+p.f.Name+"/" {
			file = source + file
		}
		names = append(names, "`"+file+"`")
	}
	return strings.Join(names, ", ")
}

// list names a set of families as prose: one family, or several joined.
func (p *page) list(names []string, one, many string) string {
	word := many
	if len(names) == 1 {
		word = one
	}
	if len(names) < 2 {
		return word + " " + p.families(names)
	}
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = "`" + name + "`"
	}
	return word + " " + strings.Join(quoted[:len(quoted)-1], ", ") + " and " + quoted[len(quoted)-1]
}

func (p *page) families(names []string) string {
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

func (p *page) types() {
	f := p.f
	if len(f.Types) > 0 {
		p.line("")
		p.line("## Types")
		p.declarations(f.Types)
	}
	if len(f.Carried) > 0 {
		p.line("")
		p.line("## Carried types")
		p.line("")
		p.linef("These are this family's own types, declared in the same language by a built-in family Nightseam declares of itself and imported by the tier that brings it, with no `imports` line. A declaration of this family may not declare one and names it by the built-in that declares it — `%s.%s`.", f.Carried[0].From, f.Carried[0].Name)
		p.declarations(f.Carried)
	}
}

func (p *page) declarations(types []*doc.Type) {
	for _, t := range types {
		p.line("")
		p.linef("### %s", t.Name)
		p.line("")
		what := t.Kind
		if t.Kind == "entity" {
			what = "entity, identified by `" + t.Key + "`"
		}
		if t.Open {
			what += ", open: fields beyond the declared ones are kept"
		}
		if len(t.Uses) > 0 {
			var names []string
			for _, use := range t.Uses {
				name := use.Parameter
				if use.Type != "" {
					name += "." + use.Type
				}
				names = append(names, code(name))
			}
			what += ", generic in " + strings.Join(names, ", ")
		}
		if t.Carried {
			what += ", carried from the built-in `" + t.From + "` family"
		}
		p.linef("%s %s.%s", article(what), what, suffix(t.Description))
		if t.Inline {
			p.line("")
			p.line("Declared inline; its name is derived from its declaration path.")
		}
		if len(t.Extends) > 0 {
			p.line("")
			var bases []string
			for _, base := range t.Extends {
				bases = append(bases, p.spell(base, t.Origin.Family, t.Scope))
			}
			p.linef("Extends %s.", strings.Join(bases, ", "))
		}
		if len(t.Parameters) > 0 {
			p.line("")
			p.line("#### Parameters")
			p.line("")
			for _, parameter := range t.Parameters {
				p.parameter(parameter)
			}
		}
		switch t.Kind {
		case "record", "entity":
			if len(t.Fields) == 0 {
				break
			}
			p.line("")
			p.line("| Field | Type | Presence | Constraints | Description |")
			p.line("|---|---|---|---|---|")
			for _, field := range t.Fields {
				presence := "required"
				if !field.Required {
					presence = "optional"
				}
				if field.Nullable {
					presence += ", nullable"
				}
				description := field.Description
				if field.Owner != t.Name || field.Origin.Family != t.Origin.Family {
					description = strings.TrimSpace("inherited from " + code(p.qualified(field.Origin.Family, field.Owner)) + ". " + description)
				}
				p.linef("| `%s` | %s | %s | %s | %s |", field.Name, cell(p.spell(field.Declared, field.Origin.Family, t.Scope)), presence, constraints(field), cell(description))
			}
		case "enum":
			var values []string
			for _, value := range t.Values {
				values = append(values, "`"+value+"`")
			}
			p.line("")
			p.linef("One of %s.", strings.Join(values, ", "))
		case "alias":
			p.line("")
			p.linef("An alias of %s.", p.spell(t.Alias, t.Origin.Family, t.Scope))
		case "union":
			p.line("")
			p.linef("The `%s` member identifies the variant. The complete payload is carried in `%s` beside the tag, including records, maps, JSON and null. A record's own literal tag remains inside its payload. A variant without a payload has only the tag; `%s` is absent.", t.Tag, t.Value, t.Value)
			p.line("")
			p.line("| Tag | Payload | Declared by |")
			p.line("|---|---|---|")
			for _, variant := range t.Variants {
				tag, _ := json.Marshal(variant.Tag)
				payload := "—"
				if variant.Declared != nil {
					payload = p.spell(variant.Declared, variant.Origin.Family, variant.Scope)
				}
				p.linef("| %s | %s | %s |", cell(code(string(tag))), cell(payload), code(p.qualified(variant.Origin.Family, variant.Origin.Declaration)))
			}
		}
		p.languageBlocks(t.Languages)
		p.example(t)
	}
}

// example writes a type's example value and where the type is used. A
// type of the profile's own — carried from a built-in, or on a built-in's
// own page — has none: its values are shaped by the profile's rules beyond
// its declaration, and an example of the declaration alone would show a
// frame that is none, where the operations show the frames as they are.
func (p *page) example(t *doc.Type) {
	if t.Carried || p.f.Builtin {
		return
	}
	p.line("")
	p.line("For example:")
	p.json(t.Example)
	if len(t.UsedBy) == 0 {
		return
	}
	// An operation using the type at more than one place is named once,
	// with its places: `echo` (request, result).
	var uses []string
	at := map[string]int{}
	for _, use := range t.UsedBy {
		if use.Kind == "type" {
			if use.At == "alias" {
				uses = append(uses, "`"+use.Name+"` (alias)")
			} else {
				uses = append(uses, "`"+use.Name+"."+use.At+"`")
			}
			continue
		}
		key := use.Kind + " " + use.Name
		if i, seen := at[key]; seen {
			uses[i] = strings.TrimSuffix(uses[i], ")") + ", " + use.At + ")"
			continue
		}
		at[key] = len(uses)
		uses = append(uses, "`"+use.Name+"` ("+use.At+")")
	}
	p.line("")
	p.linef("Used by %s.", strings.Join(uses, ", "))
}

// json writes a value as a fenced block, indented for a reader.
func (p *page) json(value json.RawMessage) {
	var b bytes.Buffer
	if err := json.Indent(&b, value, "", "  "); err != nil {
		b.Reset()
		b.Write(value)
	}
	p.line("")
	p.line("```json")
	for _, line := range strings.Split(b.String(), "\n") {
		p.line(line)
	}
	p.line("```")
}

func (p *page) side(name, intro string, side doc.Side) {
	if len(side.Methods) == 0 && len(side.Events) == 0 && len(side.Extends) == 0 {
		return
	}
	p.line("")
	p.linef("## %s side", name)
	p.line("")
	p.line(intro)
	if len(side.Extends) > 0 {
		p.line("")
		var scope []string
		for _, parameter := range p.f.Parameters {
			scope = append(scope, parameter.Name)
		}
		var bases []string
		for _, edge := range side.Extends {
			base := code(edge.Name)
			if edge.Applied() {
				base += " with " + p.fillers(edge.With, p.f.Name, scope)
			}
			bases = append(bases, base)
		}
		p.linef("Extends the %s side of %s.", strings.ToLower(name), strings.Join(bases, ", "))
	}
	if len(side.Methods) > 0 {
		p.line("")
		p.line("| Method | Request | Result | Errors | Description |")
		p.line("|---|---|---|---|---|")
		for _, m := range side.Methods {
			request := "—"
			if m.DeclaredRequest != nil {
				request = p.spell(m.DeclaredRequest, m.Origin.Family, m.Scope)
			}
			p.linef("| `%s` | %s | %s | %s | %s |", m.Name, cell(request), cell(p.spell(m.DeclaredResult, m.Origin.Family, m.Scope)), codes(m.Errors), cell(p.inherited(m.Description, m.Origin.Family)))
		}
	}
	if len(side.Events) > 0 {
		p.line("")
		p.line("| Event | Data | Description |")
		p.line("|---|---|---|")
		for _, e := range side.Events {
			p.linef("| `%s` | %s | %s |", e.Name, cell(p.spell(e.Declared, e.Origin.Family, e.Scope)), cell(p.inherited(e.Description, e.Origin.Family)))
		}
	}
	caller, callee := "client", "server"
	if name == "Client" {
		caller, callee = "server", "client"
	}
	for _, m := range side.Methods {
		p.line("")
		p.linef("### `%s` on the wire", m.Name)
		p.line("")
		p.linef("The %s sends:", caller)
		p.json(m.Frames.Request)
		p.line("")
		p.linef("The %s answers:", callee)
		p.json(m.Frames.Response)
		for _, refusal := range m.Frames.Refusals {
			p.line("")
			p.linef("Or refuses with `%s`:", refusal.Code)
			p.json(refusal.Frame)
		}
		p.languageBlocks(m.Languages)
	}
	for _, e := range side.Events {
		p.line("")
		p.linef("### `%s` on the wire", e.Name)
		p.line("")
		p.linef("The %s emits:", callee)
		p.json(e.Frame)
		p.languageBlocks(e.Languages)
	}
}

func (p *page) languageBlocks(languages map[string]doc.Language) {
	names := make([]string, 0, len(languages))
	for name := range languages {
		names = append(names, name)
	}
	sort.Strings(names)
	for _, name := range names {
		language := languages[name]
		var fragments []string
		for _, fragment := range []string{language.Declare, language.Invoke.Call, language.Invoke.Handle} {
			if fragment != "" {
				fragments = append(fragments, fragment)
			}
		}
		if len(fragments) == 0 {
			continue
		}
		source := strings.Join(fragments, "\n\n")
		fence := "```"
		for strings.Contains(source, fence) {
			fence += "`"
		}
		p.line("")
		p.linef("In %s:", code(name))
		p.line("")
		p.line(fence + name)
		for _, line := range strings.Split(source, "\n") {
			p.line(line)
		}
		p.line(fence)
	}
}

func (p *page) inherited(description, family string) string {
	if family != "" && family != p.f.Name {
		return strings.TrimSpace("Inherited from `" + family + "`. " + description)
	}
	return description
}

func (p *page) qualified(family, name string) string {
	if family != "" && family != p.f.Name {
		return family + "." + name
	}
	return name
}

// spell writes a type expression as the page reads it: a plain name that
// is a parameter in scope as itself, any other name qualified by the family
// that owns it where that is another than this one.
func (p *page) spell(e model.TypeExpr, owner string, scope []string) string {
	switch x := e.(type) {
	case model.Primitive:
		return "`" + string(x) + "`"
	case model.Named:
		for _, parameter := range scope {
			if parameter == x.Name {
				return code(x.Name)
			}
		}
		return code(p.qualified(owner, x.Name))
	case model.Imported:
		return code(p.qualified(x.Family, x.Name))
	case model.Drawn:
		return "`" + x.Parameter + "." + x.Name + "`"
	case model.Array:
		return "array of " + p.spell(x.Elem, owner, scope)
	case model.Map:
		return "map of " + p.spell(x.Elem, owner, scope)
	case model.Nullable:
		return "nullable " + p.spell(x.Elem, owner, scope)
	case model.Literal:
		value, _ := json.Marshal(x.Value)
		return "the literal " + code(string(value))
	case model.Ref:
		family := x.Family
		if family == "" {
			family = owner
		}
		return "reference to " + code(p.qualified(family, x.Entity))
	case model.Apply:
		family := x.Family
		if family == "" {
			family = owner
		}
		return code(p.qualified(family, x.Name)) + " with " + p.fillers(x.With, owner, scope)
	}
	return "`" + model.String(e) + "`"
}

func (p *page) fillers(bindings map[string]model.Filler, owner string, scope []string) string {
	var with []string
	for _, parameter := range sortedKeys(bindings) {
		filler := bindings[parameter]
		value := filler.Family
		if value == "" {
			value = p.spell(filler.Type, owner, scope)
		}
		with = append(with, parameter+"="+value)
	}
	return strings.Join(with, ", ")
}

// code uses a delimiter longer than any backtick run in a literal, so its
// Markdown representation preserves the string rather than ending early.
func code(value string) string {
	delimiter := "`"
	for strings.Contains(value, delimiter) {
		delimiter += "`"
	}
	return delimiter + value + delimiter
}

// article is the indefinite article a word takes.
func article(word string) string {
	if strings.HasPrefix(word, "union") {
		return "A"
	}
	if strings.ContainsRune("aeiou", rune(word[0])) {
		return "An"
	}
	return "A"
}

// constraints lists a field's constraints, or nothing.
func constraints(field doc.Field) string {
	var out []string
	if field.Unique {
		out = append(out, "unique")
	}
	if field.Min != nil {
		out = append(out, "min "+field.Min.String())
	}
	if field.Max != nil {
		out = append(out, "max "+field.Max.String())
	}
	if field.Length != nil {
		if field.Length.Min != nil {
			out = append(out, fmt.Sprintf("length ≥ %d", *field.Length.Min))
		}
		if field.Length.Max != nil {
			out = append(out, fmt.Sprintf("length ≤ %d", *field.Length.Max))
		}
	}
	if field.Pattern != "" {
		out = append(out, "matches `"+field.Pattern+"`")
	}
	if len(out) == 0 {
		return "—"
	}
	return cell(strings.Join(out, ", "))
}

func codes(names []string) string {
	if len(names) == 0 {
		return "—"
	}
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

// cell makes text safe in a table cell.
func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(text), "|", "\\|"), "\n", " ")
}

// suffix appends a description as a second sentence, or nothing.
func suffix(description string) string {
	if strings.TrimSpace(description) == "" {
		return ""
	}
	return " " + strings.TrimSpace(description)
}

func sortedKeys(m map[string]model.Filler) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
