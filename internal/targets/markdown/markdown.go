// Package markdown writes the document as Markdown: one page per family,
// README.md under api/spec/<family>, which renders where the tree is read —
// the types with their fields and constraints, the two sides with their
// operations and errors, the parameters a family is generic in, the
// governance of a session of it — so that what a family means is written
// once, in the declaration, and the page is never behind it. It is a
// doc.Writer, a target by doc.Target, and reserves nothing: it declares no
// identifier a family could collide with.
package markdown

import (
	"fmt"
	"path"
	"sort"
	"strings"

	"github.com/Bitspark/nightseam/internal/doc"
	"github.com/Bitspark/nightseam/internal/emit"
	"github.com/Bitspark/nightseam/internal/model"
	"github.com/Bitspark/nightseam/internal/spi"
)

// Config places the pages: Layout is where a family's page lives, as a
// pattern over the family's name; Place puts named families elsewhere.
type Config struct {
	Layout string
	Place  map[string]string
}

// DefaultLayout is api/spec/<family>, holding README.md.
const DefaultLayout = "api/spec/{family}"

// Name is the writer's name, and its target's.
const Name = "markdown"

// File is the page's name within the family's directory.
const File = "README.md"

// New returns the Markdown writer with its config.
func New(c Config) doc.Writer {
	if c.Layout == "" {
		c.Layout = DefaultLayout
	}
	return &writer{c}
}

type writer struct{ config Config }

func (*writer) Name() string { return Name }

func (w *writer) Layout() doc.Layout {
	return doc.Layout{Family: w.config.Layout, Place: w.config.Place}
}

// Reserved is what the writer reserves: nothing.
func Reserved() []string { return nil }

// Checkout writes no page of the checkout as a whole.
func (*writer) Checkout(*doc.Checkout) ([]spi.File, error) { return nil, nil }

// Family writes the family's page.
func (w *writer) Family(f *doc.Family) ([]spi.File, error) {
	out := emit.NewWriter("")
	p := &page{f: f, w: out}
	p.render()
	return []spi.File{{Path: path.Join(w.Layout().Dir(f.Name), File), Data: []byte(out.String())}}, nil
}

type page struct {
	f *doc.Family
	w *emit.Writer
}

func (p *page) line(text string)                 { p.w.Line(text) }
func (p *page) linef(format string, args ...any) { p.w.Linef(format, args...) }

func (p *page) render() {
	f := p.f
	p.linef("# %s", f.Name)
	p.line("")
	p.line("<!-- Generated by nightseam from api/contracts/" + f.Name + "/; do not edit. -->")
	p.line("")
	p.linef("A family of the `nightseam.duplex/1` profile, declared in %s.", p.tiers())
	if len(f.Imports) > 0 {
		p.linef("It imports %s.", p.families(f.Imports))
	}
	if len(f.Carries) > 0 {
		p.linef("The tiers it declares bring the built-in %s, imported implicitly.", p.list(f.Carries, "family", "families"))
	}
	if f.Generic {
		p.line("")
		p.line("## Parameters")
		p.line("")
		p.line("The family is generic in the families bound to these parameters, where its generated code is instantiated:")
		p.line("")
		for _, parameter := range f.Parameters {
			var drawn []string
			for _, name := range parameter.Drawn {
				drawn = append(drawn, "`"+name+"`")
			}
			p.linef("- **%s**, of the `%s` role, drawn at %s.%s", parameter.Name, parameter.Of, strings.Join(drawn, ", "), suffix(parameter.Description))
		}
	}
	p.types()
	if f.Protocol {
		p.side("Server", "The server implements these methods and emits these events.", f.Server)
		p.side("Client", "The client implements these methods, which the server calls, and emits these events.", f.Client)
		if len(f.Errors) > 0 {
			p.line("")
			p.line("## Errors")
			p.line("")
			p.line("The public errors of the family, by code: what a call may fail with.")
			p.line("")
			p.line("| Code | Description |")
			p.line("|---|---|")
			for _, e := range f.Errors {
				p.linef("| `%s` | %s |", e.Code, cell(e.Description))
			}
		}
	}
	if s := f.Session; s != nil {
		p.line("")
		p.line("## Session")
		p.line("")
		p.line("How a session of the family is governed.")
		p.line("")
		p.linef("- **Decides**: %s — the methods that need control to send.", codes(s.Decides))
		p.linef("- **Asks**: %s — the methods the server sends that raise a request the holder of control must answer.", codes(s.Asks))
		if s.Conversation != nil {
			p.linef("- **Conversation**: the id arrives in the `%s` event, at `%s` of its data.", s.Conversation.Event, s.Conversation.Path)
		}
	}
}

func (p *page) tiers() string {
	var names []string
	for _, file := range p.f.Files {
		names = append(names, "`"+file+"`")
	}
	return strings.Join(names, ", ")
}

// list names a set of families as prose: one family, or several joined.
func (p *page) list(names []string, one, many string) string {
	word := many
	if len(names) == 1 {
		word = one
	}
	if len(names) < 2 {
		return word + " " + p.families(names)
	}
	quoted := make([]string, len(names))
	for i, name := range names {
		quoted[i] = "`" + name + "`"
	}
	return word + " " + strings.Join(quoted[:len(quoted)-1], ", ") + " and " + quoted[len(quoted)-1]
}

func (p *page) families(names []string) string {
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

func (p *page) types() {
	f := p.f
	if len(f.Types) > 0 {
		p.line("")
		p.line("## Types")
		p.declarations(f.Types)
	}
	if len(f.Carried) > 0 {
		p.line("")
		p.line("## Carried types")
		p.line("")
		p.linef("These are this family's own types, declared in the same language by a built-in family Nightseam declares of itself and imported by the tier that brings it, with no `imports` line. A declaration of this family may not declare one and names it by the built-in that declares it — `%s.%s`.", f.Carried[0].From, f.Carried[0].Name)
		p.declarations(f.Carried)
	}
}

func (p *page) declarations(types []*doc.Type) {
	for _, t := range types {
		p.line("")
		p.linef("### %s", t.Name)
		p.line("")
		what := t.Kind
		if t.Kind == "entity" {
			what = "entity, identified by `" + t.Key + "`"
		}
		if t.Open {
			what += ", open: fields beyond the declared ones are kept"
		}
		if len(t.Uses) > 0 {
			var names []string
			for _, use := range t.Uses {
				names = append(names, "`"+use.Parameter+"."+use.Type+"`")
			}
			what += ", generic in " + strings.Join(names, ", ")
		}
		if t.Carried {
			what += ", carried from the built-in `" + t.From + "` family"
		}
		p.linef("%s %s.%s", article(what), what, suffix(t.Description))
		switch t.Kind {
		case "record", "entity":
			if len(t.Fields) == 0 {
				continue
			}
			p.line("")
			p.line("| Field | Type | Presence | Constraints | Description |")
			p.line("|---|---|---|---|---|")
			for _, field := range t.Fields {
				presence := "required"
				if !field.Required {
					presence = "optional"
				}
				if field.Nullable {
					presence += ", nullable"
				}
				description := field.Description
				if field.Owner != t.Name {
					description = strings.TrimSpace("inherited from `" + field.Owner + "`. " + description)
				}
				p.linef("| `%s` | %s | %s | %s | %s |", field.Name, spell(field.Type), presence, constraints(field), cell(description))
			}
		case "enum":
			var values []string
			for _, value := range t.Values {
				values = append(values, "`"+value+"`")
			}
			p.line("")
			p.linef("One of %s.", strings.Join(values, ", "))
		case "alias":
			p.line("")
			p.linef("An alias of %s.", spell(t.Alias))
		}
	}
}

func (p *page) side(name, intro string, side doc.Side) {
	if len(side.Methods) == 0 && len(side.Events) == 0 {
		return
	}
	p.line("")
	p.linef("## %s side", name)
	p.line("")
	p.line(intro)
	if len(side.Methods) > 0 {
		p.line("")
		p.line("| Method | Request | Result | Errors | Description |")
		p.line("|---|---|---|---|---|")
		for _, m := range side.Methods {
			request := "—"
			if m.Request != nil {
				request = spell(m.Request)
			}
			p.linef("| `%s` | %s | %s | %s | %s |", m.Name, request, spell(m.Result), codes(m.Errors), cell(m.Description))
		}
	}
	if len(side.Events) > 0 {
		p.line("")
		p.line("| Event | Data | Description |")
		p.line("|---|---|---|")
		for _, e := range side.Events {
			p.linef("| `%s` | %s | %s |", e.Name, spell(e.Type), cell(e.Description))
		}
	}
}

// spell writes a type expression as the page reads it.
func spell(e model.TypeExpr) string {
	switch x := e.(type) {
	case model.Primitive:
		return "`" + string(x) + "`"
	case model.Named:
		return "`" + x.Name + "`"
	case model.Imported:
		return "`" + x.Family + "." + x.Name + "`"
	case model.Drawn:
		return "`" + x.Parameter + "." + x.Name + "`"
	case model.Array:
		return "array of " + spell(x.Elem)
	case model.Map:
		return "map of " + spell(x.Elem)
	case model.Ref:
		return "reference to `" + x.Entity + "`"
	case model.Apply:
		var with []string
		for _, parameter := range sortedKeys(x.With) {
			with = append(with, parameter+"="+x.With[parameter].String())
		}
		return "`" + x.Family + "." + x.Name + "` with " + strings.Join(with, ", ")
	}
	return "`" + model.String(e) + "`"
}

// article is the indefinite article a word takes.
func article(word string) string {
	if strings.ContainsRune("aeiou", rune(word[0])) {
		return "An"
	}
	return "A"
}

// constraints lists a field's constraints, or nothing.
func constraints(field doc.Field) string {
	var out []string
	if field.Unique {
		out = append(out, "unique")
	}
	if field.Min != nil {
		out = append(out, "min "+field.Min.String())
	}
	if field.Max != nil {
		out = append(out, "max "+field.Max.String())
	}
	if field.Length != nil {
		if field.Length.Min != nil {
			out = append(out, fmt.Sprintf("length ≥ %d", *field.Length.Min))
		}
		if field.Length.Max != nil {
			out = append(out, fmt.Sprintf("length ≤ %d", *field.Length.Max))
		}
	}
	if field.Pattern != "" {
		out = append(out, "matches `"+field.Pattern+"`")
	}
	if len(out) == 0 {
		return "—"
	}
	return cell(strings.Join(out, ", "))
}

func codes(names []string) string {
	if len(names) == 0 {
		return "—"
	}
	var out []string
	for _, name := range names {
		out = append(out, "`"+name+"`")
	}
	return strings.Join(out, ", ")
}

// cell makes text safe in a table cell.
func cell(text string) string {
	return strings.ReplaceAll(strings.ReplaceAll(strings.TrimSpace(text), "|", "\\|"), "\n", " ")
}

// suffix appends a description as a second sentence, or nothing.
func suffix(description string) string {
	if strings.TrimSpace(description) == "" {
		return ""
	}
	return " " + strings.TrimSpace(description)
}

func sortedKeys(m map[string]model.Filler) []string {
	keys := make([]string, 0, len(m))
	for key := range m {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}
