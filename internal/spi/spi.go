// Package spi is the seam between the kernel and the targets it renders
// with. A target sees a family as render presents it and answers with the
// sources it owns; the kernel never names a target, and a target never
// sees the kernel, the loader or another target. They meet only where the
// tool is composed.
package spi

import (
	"regexp"
	"strings"

	"github.com/Bitspark/nightseam/internal/diag"
	"github.com/Bitspark/nightseam/internal/render"
)

// Concern is a tier a target consumes, by name.
type Concern = string

// The concerns.
const (
	Model    Concern = "model"
	Protocol Concern = "protocol"
	Session  Concern = "session"
)

// Header opens every generated file, in every language.
const Header = "// Code generated by nightseam. DO NOT EDIT.\n"

// Target renders one family for one technology.
type Target interface {
	// Name identifies the target in diagnostics and names its override
	// file, <name>.json.
	Name() string
	// Consumes names the concerns the target reads; a family that has none
	// of them beyond the model is not rendered by it.
	Consumes() []Concern
	// Owns names the directories the target's rendering of a family lives
	// in, relative to the checkout: the generator owns them wholesale and a
	// human writes nothing there. Every rendered path lies under one. The
	// checkout as a whole is the family "", the name the kernel gives the
	// checkout's own diagnostics: a CheckoutRenderer answers Owns("") with
	// the directories its files of the checkout lie under, and no other
	// target is asked it.
	Owns(family string) []string
	// Roots names the directories under which the target places every
	// family's rendering, relative to the checkout: where a rendering of a
	// family that no longer exists would be found.
	Roots() []string
	// Family answers a path under a root with the family whose rendering
	// it belongs to, by the target's layout — "" for a file of the checkout
	// as a whole — or false for a path that is nobody's — what a tool
	// installed beside a rendering, say — which the generator leaves alone.
	Family(path string) (string, bool)
	// Check reports what the family would make the target render that it
	// cannot: the names its override file gives, the identifiers it would
	// declare, the collisions among them. It runs on a family every
	// neutral check accepted.
	Check(f *render.Family) []diag.Diagnostic
	// Render emits the family's sources. Paths are slash-separated and
	// relative to the checkout; the kernel refuses one outside what the
	// target owns.
	Render(f *render.Family) ([]File, error)
}

// Scaffolder is a target that can write the hand-written side of a slot
// once: an implementation of what its rendering declares — a server's
// handler, a client's handler of what the server sends — into a directory
// of the consumer's own, for the consumer to fill in. The generator writes
// it on request and never again.
type Scaffolder interface {
	// Scaffold renders the stubs for a family into dir, relative to the
	// checkout; each file's path lies under dir.
	Scaffold(f *render.Family, dir string) ([]File, error)
}

// CheckoutRenderer is a target that renders files of the checkout as a
// whole, which are no family's: an index of every family, a page that
// shows them side by side. The kernel renders them on every run, after the
// families, from every family the checkout has, and never counts one a
// leftover; they lie under what Owns("") names, and Family answers "" for
// them.
type CheckoutRenderer interface {
	// RenderCheckout emits the checkout's files. Paths are slash-separated
	// and relative to the checkout.
	RenderCheckout(w *render.World) ([]File, error)
}

// File is one rendered source.
type File struct {
	Path string
	Data []byte
}

// A target lays a family's rendering out by patterns over the family's
// name, {family}: api/go/{family}-protocol. PatternRoot and MatchPattern
// are the two questions the kernel asks of one.

// PatternRoot is the directory a pattern places every family under: the
// pattern up to the last separator before {family}, or "." when there is
// none.
func PatternRoot(pattern string) string {
	before, _, _ := strings.Cut(pattern, "{family}")
	if at := strings.LastIndex(before, "/"); at >= 0 {
		return before[:at]
	}
	return "."
}

// MatchPattern reads the family out of a path a pattern places: the path
// must begin with the pattern's directory, {family} filling one segment's
// worth of a family name.
func MatchPattern(pattern, p string) (string, bool) {
	before, after, _ := strings.Cut(pattern, "{family}")
	if !strings.HasPrefix(p, before) {
		return "", false
	}
	rest := strings.TrimPrefix(p, before)
	segment, _, _ := strings.Cut(rest, "/")
	if !strings.HasSuffix(segment, after) || len(segment) <= len(after) {
		return "", false
	}
	family := strings.TrimSuffix(segment, after)
	if !familyPattern.MatchString(family) {
		return "", false
	}
	return family, true
}

var familyPattern = regexp.MustCompile(`^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$`)
