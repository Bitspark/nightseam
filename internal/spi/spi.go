// Package spi is the seam between the generation kernel and the languages it
// renders. A language sees the parsed contract and answers with the sources
// it owns; the kernel never names a language, and a language never sees the
// kernel or another language. They meet only where the tool is composed.
package spi

import "github.com/Bitspark/nighthall/tools/go/generate-api/internal/contract"

// Recipe names the generation recipe every language renders; RuntimeVersion
// the runtime the rendered sources bind to.
const Recipe = "websocket-api/1"
const RuntimeVersion = "1"

// Header opens every generated file, in every language.
const Header = "// Code generated by dev websocket-api/1. DO NOT EDIT.\n"

// Language renders one API family for one target language.
type Language interface {
	// Name identifies the language in diagnostics and listings: "go", "typescript".
	Name() string
	// Check reports what the contract would make this language generate that
	// it cannot: reserved identifiers, collisions in generated namespaces. It
	// runs on any contract the schema accepts, so it tolerates unresolved
	// types and inheritance cycles; pointers follow the contract's convention.
	Check(api contract.API) []contract.Diagnostic
	// Render emits the family's sources for a contract every language
	// accepted. Paths are slash-separated and relative to the repository
	// root; the kernel rejects one that escapes it.
	Render(api contract.API) ([]File, error)
}

// File is one rendered source.
type File struct {
	Path string
	Data []byte
}
