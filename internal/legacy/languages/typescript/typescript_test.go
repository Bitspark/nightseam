func contractFixture(t *testing.T) map[string]any {
	t.Helper()
	var value map[string]any
	err := json.Unmarshal([]byte(`{"schema_version":1,"profile":"nightseam.duplex/1","name":"example","types":{"Input":{"kind":"record","fields":[{"name":"message","type":"string"},{"name":"count","type":"integer","required":false,"nullable":true}]},"Result":{"kind":"record","fields":[{"name":"ok","type":"boolean"}]}},"methods":[{"name":"example.run","go_name":"Run","ts_name":"run","direction":"client_to_server","request":"Input","result":"Result"}],"events":[{"name":"example.changed","go_name":"Changed","ts_name":"changed","direction":"server_to_client","type":"Result"}]}`), &value)
	if err != nil {
		t.Fatal(err)
	}
	return value
}

// check parses a contract the schema accepts and returns what TypeScript refuses in it.
func check(t *testing.T, v map[string]any) []contract.Diagnostic {
	t.Helper()
	api, diagnostics := contract.Parse(v)
	if len(diagnostics) != 0 {
		t.Fatalf("schema refused the fixture: %+v", diagnostics)
	}
	return New(Options{}).Check(api)
}

// TestCheckRejectsWhatTypeScriptCannotGenerate breaks the fixture one way at
// a time and expects the TypeScript language to name it, at the pointer of
// the name.
func TestCheckRejectsWhatTypeScriptCannotGenerate(t *testing.T) {
	tests := []struct {
		name, code, pointer string
		mutate              func(map[string]any)
	}{
		{"thenable client method", "reserved_name", "/methods/0/ts_name", func(v map[string]any) { v["methods"].([]any)[0].(map[string]any)["ts_name"] = "then" }},
		{"reserved word", "reserved_name", "/methods/0/ts_name", func(v map[string]any) { v["methods"].([]any)[0].(map[string]any)["ts_name"] = "delete" }},
		{"event helper collision", "generated_name_collision", "/events/0/ts_name", func(v map[string]any) { v["methods"].([]any)[0].(map[string]any)["ts_name"] = "onChanged" }},
		{"constructor collision", "generated_name_collision", "/methods/0/ts_name", func(v map[string]any) { v["methods"].([]any)[0].(map[string]any)["ts_name"] = "constructor" }},
		{"TypeScript operation collision", "operation_collision", "/methods/1/ts_name", func(v map[string]any) {
			v["methods"] = append(v["methods"].([]any), map[string]any{"name": "other", "go_name": "Other", "ts_name": "run", "direction": "client_to_server", "result": "Result"})
		}},
		{"reserved type", "reserved_name", "/types/Client", func(v map[string]any) {
			v["types"].(map[string]any)["Client"] = map[string]any{"kind": "record", "fields": []any{}}
		}},
		{"global type", "reserved_name", "/types/Date", func(v map[string]any) {
			v["types"].(map[string]any)["Date"] = map[string]any{"kind": "alias", "type": "timestamp"}
		}},
		{"error member collision", "generated_name_collision", "/errors/1/code", func(v map[string]any) {
			v["errors"] = []any{map[string]any{"code": "not-found", "description": ""}, map[string]any{"code": "not_found", "description": ""}}
		}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			v := contractFixture(t)
			tt.mutate(v)
			diagnostics := check(t, v)
			for _, d := range diagnostics {
				if d.Code == tt.code && d.Pointer == tt.pointer {
					return
				}
			}
			t.Fatalf("expected %s at %s, got %+v", tt.code, tt.pointer, diagnostics)
		})
	}
	if diagnostics := check(t, contractFixture(t)); len(diagnostics) != 0 {
		t.Fatalf("the fixture is refused: %+v", diagnostics)
	}
}

// TestRenderPlacesTheClient renders the fixture alone, as TypeScript, and
// holds the package layout and the option rule.
func TestRenderPlacesTheClient(t *testing.T) {
	api, diagnostics := contract.Parse(contractFixture(t))
	if len(diagnostics) != 0 {
		t.Fatal(diagnostics)
	}
	files, err := New(Options{Scope: "@example"}).Render(api)
	if err != nil {
		t.Fatal(err)
	}
	var paths []string
	for _, file := range files {
		paths = append(paths, file.Path)
	}
	if strings.Join(paths, " ") != "api/ts/example-client/src/types.ts api/ts/example-client/src/index.ts api/ts/example-client/package.json api/ts/example-client/tsconfig.json" {
		t.Fatalf("unexpected layout: %v", paths)
	}
	if !strings.HasPrefix(string(files[0].Data), "// Code generated by nightseam. DO NOT EDIT.\n") || !strings.Contains(string(files[1].Data), "async run(params: Protocol.Input") {
		t.Fatalf("unexpected sources:\n%s\n%s", files[0].Data, files[1].Data)
	}
	if !strings.Contains(string(files[2].Data), `"name":"@example/example-client"`) {
		t.Fatalf("unexpected manifest: %s", files[2].Data)
	}
	for _, options := range []Options{{}, {Scope: "example"}, {Scope: "@example", ClientPath: "../outside"}, {Scope: "@example", ClientPath: "/abs"}, {Scope: "@example", ClientPath: "api/ts/x/"}, {Scope: "@example", ClientPath: "api\\ts"}} {
		if _, err := New(options).Render(api); err == nil {
			t.Errorf("accepted options %+v", options)
		}
	}
	files, err = New(Options{Scope: "@example", ClientPath: "gen/ts"}).Render(api)
	if err != nil {
		t.Fatal(err)
	}
	if files[0].Path != "gen/ts/src/types.ts" {
		t.Fatalf("option was not honoured: %s", files[0].Path)
	}
}
