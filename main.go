// generate-api renders the checked-in API contracts with the duplex generator
// copied from Nightshift (docs/DECISIONS.md, D-001). It is developer tooling,
// never a runtime dependency: the generated packages depend only on the
// protocol types and api/go/ws-runtime.
//
//	go run ./tools/go/generate-api            render every family
//	go run ./tools/go/generate-api hall       render one
//	go run ./tools/go/generate-api --check    fail if checked-in output is stale
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"sort"

	"github.com/Bitspark/nighthall/tools/go/generate-api/internal/generate"
)

// module is the import path the generated Go packages are rooted at.
const module = "github.com/Bitspark/nighthall"

// families are the three application APIs. A contract lives at
// api/contracts/<family>.json and is the spec.api document itself.
var families = []string{"hall", "harness", "session"}

func main() {
	root := flag.String("root", ".", "repository root")
	check := flag.Bool("check", false, "compare generated bytes with the checked-in output without writing")
	flag.Parse()
	names := flag.Args()
	if len(names) == 0 {
		names = families
	}
	if err := run(*root, names, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func loadContract(root, name string) (map[string]any, error) {
	known := false
	for _, family := range families {
		known = known || family == name
	}
	if !known {
		return nil, fmt.Errorf("unknown API %q; the families are %v", name, families)
	}
	data, err := os.ReadFile(filepath.Join(root, "api", "contracts", name+".json"))
	if err != nil {
		return nil, err
	}
	var contract map[string]any
	decoder := json.NewDecoder(bytes.NewReader(data))
	decoder.UseNumber()
	if err := decoder.Decode(&contract); err != nil {
		return nil, fmt.Errorf("%s contract: %w", name, err)
	}
	if contract["name"] != name {
		return nil, fmt.Errorf("%s contract names API %v", name, contract["name"])
	}
	return contract, nil
}

func run(root string, names []string, check bool) error {
	files := map[string][]byte{}
	for _, name := range names {
		contract, err := loadContract(root, name)
		if err != nil {
			return err
		}
		result, err := generate.Generate(contract, generate.Options{Module: module})
		if err != nil {
			return fmt.Errorf("%s: %w", name, err)
		}
		for path, data := range result.Files {
			if previous, exists := files[path]; exists && !bytes.Equal(previous, data) {
				return fmt.Errorf("conflicting generated output %s", path)
			}
			files[path] = data
		}
	}
	paths := make([]string, 0, len(files))
	for path := range files {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	stale := false
	for _, path := range paths {
		destination := filepath.Join(root, filepath.FromSlash(path))
		current, err := os.ReadFile(destination)
		if err != nil && !os.IsNotExist(err) {
			return err
		}
		if bytes.Equal(current, files[path]) {
			continue
		}
		if check {
			fmt.Fprintln(os.Stderr, "stale generated output:", path)
			stale = true
			continue
		}
		if err := os.MkdirAll(filepath.Dir(destination), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(destination, files[path], 0o644); err != nil {
			return err
		}
		fmt.Println("generated", path)
	}
	if stale {
		return fmt.Errorf("generated APIs are stale; run go run ./tools/go/generate-api")
	}
	return nil
}
